    if (this.mediaStream) {
      const videoEl = document.getElementById('proctor-video');
      if (videoEl) {
        videoEl.srcObject = this.mediaStream;
        videoEl.onloadedmetadata = () => {
          this.captureSnapshot(videoEl);
          this.initProctoring(videoEl);
        };
      }
    } else {
      this.initProctoring(null);
    }

    // Start Timer
    this.startTimer();
